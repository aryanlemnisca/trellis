/*
 * Builds standalone/index.html: the whole site in ONE file (CSS, JS, fonts,
 * logo and favicon inlined), for hosting anywhere with no build step.
 *
 *   npm run build:standalone                  # dev defaults (noindex); webhook from .env / env
 *   SITE_URL=https://example.com SITE_INDEXABLE=true npm run build:standalone
 *
 * It post-processes the real Astro build (dist/), so it always matches the site.
 * The form webhook IS baked in (PUBLIC_DEMO_FORM_HOOK from env or .env). The <meta name="demo-form-hook"> tag overrides it when filled.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { rolldown } from 'rolldown';
import sharp from 'sharp';

const root = new URL('../', import.meta.url);

/* The demo-form webhook is baked into the standalone file (a deliberate choice: it is public in any hosted page anyway).
   Source: env PUBLIC_DEMO_FORM_HOOK, else .env. Empty = the form shows "not connected" until the meta tag is filled in. */
const envFile = (() => { try { return readFileSync(new URL('../.env', import.meta.url), 'utf8'); } catch { return ''; } })();
const hook = process.env.PUBLIC_DEMO_FORM_HOOK || (envFile.match(/^PUBLIC_DEMO_FORM_HOOK=(.+)$/m) || [])[1] || '';
const p = (rel) => new URL(rel, root).pathname;
const b64 = (buf) => Buffer.from(buf).toString('base64');

execSync('npx astro build', { cwd: p('.'), stdio: 'inherit', env: { ...process.env, PUBLIC_DEMO_FORM_HOOK: '' } });
let html = readFileSync(p('dist/index.html'), 'utf8');

/* ---- CSS: inline, keep only the Latin (+ symbols) font subsets, fonts as data URIs ---- */
const cssHref = html.match(/<link rel="stylesheet" href="([^"]+\.css)">/)[1];
let css = readFileSync(p('dist' + cssHref), 'utf8');
css = css.replace(/@font-face\{[^}]*\}/g, (face) => {
  const m = face.match(/url\((\/_assets\/[^)]*-(latin|symbols2)-\d+-normal\.[^)]*\.woff2)\)/);
  if (!m) return ''; // drop cyrillic, vietnamese, latin-ext: the copy needs none of them
  const font = readFileSync(p('dist' + m[1]));
  return face.replace(/src:[^;]*;/, `src:url(data:font/woff2;base64,${b64(font)})format("woff2");`);
});
css += '\n' + readFileSync(p('node_modules/lenis/dist/lenis.css'), 'utf8');
html = html.replace(/<link rel="stylesheet" href="[^"]+">/, () => `<style>${css}</style>`);

/* ---- JS: one IIFE bundle of the same sources the site uses ---- */
const entry = p('scripts/.standalone-entry.js');
writeFileSync(entry, `import '../src/scripts/global.js';\nimport '../src/scripts/pages/home.js';\n`);
const bundle = await rolldown({
  input: entry,
  plugins: [{
    name: 'stub-css', // CSS is inlined separately above; scripts only import it for the Astro build
    resolveId: (id) => (id.endsWith('.css') ? '\0empty-css' : null),
    load: (id) => (id === '\0empty-css' ? { code: 'export default ""', moduleType: 'js' } : null),
  }],
  transform: { define: { 'import.meta.env.PUBLIC_DEMO_FORM_HOOK': JSON.stringify(hook) } },
});
const { output } = await bundle.generate({ format: 'iife', minify: true });
const js = output.find((o) => o.type === 'chunk').code.replace(/<\/script/gi, '<\\/script');
html = html.replace(/<script type="module" src="[^"]+"><\/script>\s*/g, '');
html = html.replace('</body>', () => `<script>${js}</script>\n</body>`);

/* ---- images: logo (as WebP, ~10x smaller) and favicon ---- */
const logoWebp = await sharp(readFileSync(p('public/trellis-logo.png'))).webp({ quality: 92, alphaQuality: 100 }).toBuffer();
html = html.replaceAll('src="/trellis-logo.png"', `src="data:image/webp;base64,${b64(logoWebp)}"`);
html = html.replace(/href="\/favicon\.svg"/, `href="data:image/svg+xml;base64,${b64(readFileSync(p('public/favicon.svg')))}"`);

/* ---- drop references to files that do not exist in a single-file build ---- */
html = html.replace(/<link rel="(sitemap|alternate)"[^>]*>\s*/g, '');

/* ---- hosting notes + the one setting to fill in ---- */
html = html.replace(
  /<head>/,
  `<head>
<!-- Trellis site, standalone single-file build. GENERATED by scripts/build-standalone.mjs - edit the source in src/, not this file.
     To host: upload this one file as index.html. The demo form webhook is built in; to point it elsewhere, fill the demo-form-hook meta tag below.
     To change the domain / allow indexing: rebuild with SITE_URL=... SITE_INDEXABLE=true npm run build:standalone -->
<meta name="demo-form-hook" content="">`,
);

mkdirSync(p('standalone'), { recursive: true });
writeFileSync(p('standalone/index.html'), html);
execSync(`rm -f ${JSON.stringify(entry)}`);
const kb = (Buffer.byteLength(html) / 1024).toFixed(0);
const external = [...html.matchAll(/(?:src|href)="(https?:\/\/[^"]+)"/g)].map((m) => m[1]).filter((u) => !/schema\.org|w3\.org/.test(u));
console.log(`standalone/index.html written: ${kb} KB. Absolute URLs left in markup (canonical/OG only):`);
external.forEach((u) => console.log('  ', u));
